const isoDay = (date: Date) =>
  `${date.getFullYear()}-${String(date.getMonth() + 1).padStart(2, "0")}-${String(date.getDate()).padStart(2, "0")}`;
const relativeDay = (now: Date, offset: number) => {
  const date = new Date(
    now.getFullYear(),
    now.getMonth(),
    now.getDate() + offset,
    12,
  );
  return isoDay(date);
};

