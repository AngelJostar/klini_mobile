import { chromium, expect } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
import { createDemoState } from '../src/domain/seed';
import { STORAGE_KEY } from '../src/domain/reducer';
const origin = 'http://127.0.0.1:8097';
async function main() {
 const browser = await chromium.launch({channel:'chrome',headless:true});
 const results = [];
 try {
 for(const width of [390,320]) {
  const context=await browser.newContext({viewport:{width,height:width===320?640:844},reducedMotion:'reduce'});
  const errors:string[]=[];const posts:string[]=[];
  await context.route('**/*',async route=>{const req=route.request();const url=new URL(req.url());if(url.origin!==origin||req.method()!=='GET'){if(req.method()!=='GET')posts.push(req.method()+' '+url.pathname);await route.abort();}else await route.continue();});
  await context.addInitScript(({state,key})=>{if(!sessionStorage.getItem('pharmacy-qa')){localStorage.setItem(key,JSON.stringify(state));sessionStorage.setItem('pharmacy-qa','1');}}, {state:createDemoState(),key:STORAGE_KEY});
  const page=await context.newPage(); page.on('pageerror',e=>errors.push(e.message));
  await page.goto(origin+'/pharmacy');await expect(page.getByTestId('pharmacy-search')).toBeVisible({timeout:90000});
  await mkdir('test-results/pharmacy',{recursive:true});
  await page.screenshot({path:'test-results/pharmacy/catalog-'+width+'.png'});
  await page.getByTestId('pharmacy-filters').click();
  await page.screenshot({path:'test-results/pharmacy/filters-'+width+'.png'});
  await page.keyboard.press('Escape');
  await expect(page.getByTestId('pharmacy-apply-filters')).toHaveCount(0);
  await page.getByTestId('pharmacy-filters').click();
  await page.getByRole('checkbox',{name:'Solo promociones',exact:true}).click();
  await page.getByTestId('pharmacy-apply-filters').click();
  await expect(page.getByTestId('pharmacy-product-demo-sunscreen')).toBeVisible();
  await expect(page.getByTestId('pharmacy-product-demo-cleanser')).toHaveCount(0);
  await page.getByRole('button',{name:'Borrar filtros',exact:true}).click();
  await page.getByTestId('pharmacy-search').fill('no-existe');
  await expect(page.getByText('Sin productos',{exact:true})).toBeVisible();
  await page.getByTestId('pharmacy-search').fill('');
  await page.getByTestId('pharmacy-product-demo-sunscreen').click();
  await expect(page.getByTestId('pharmacy-seller-popup')).toBeVisible();
  await page.getByTestId('pharmacy-seller-option-demo-sunscreen').click();
  await page.getByTestId('pharmacy-seller-add').click();
  await expect(page.getByText('Producto agregado al carrito.')).toBeVisible();
  await page.getByRole('button',{name:'Agregar Gel limpiador',exact:true}).click();
  await page.getByTestId('pharmacy-seller-option-demo-cleanser').click();
  await page.getByTestId('pharmacy-seller-add').click();
  await page.getByTestId('pharmacy-cart').click();
  await expect(page.getByText('$549 MXN',{exact:true})).toBeVisible();
  await page.getByTestId('pharmacy-checkout').click();
  await expect(page.getByTestId('pharmacy-address-next')).toBeDisabled();
  await page.getByLabel('Nombre',{exact:true}).fill('Paciente QA');
  await page.getByLabel('Calle y número',{exact:true}).fill('Calle Ejemplo 123');
  await page.getByLabel('Colonia',{exact:true}).fill('Colonia de ejemplo');
  await page.getByLabel('Código postal',{exact:true}).fill('03100');
  await page.getByTestId('pharmacy-address-next').click();
  await page.getByRole('button',{name:'Pago de ejemplo: Apple Pay',exact:true}).click();
  await page.getByRole('checkbox',{name:'Tarjeta · ejemplo',exact:true}).click();
  await page.getByRole('button',{name:'Continuar',exact:true}).click();
  await page.getByRole('checkbox',{name:'Acepto las condiciones de la demostración',exact:true}).click();
  await page.evaluate((key) => {
    const original = Storage.prototype.setItem;
    let failures = 1;
    Storage.prototype.setItem = function(storageKey: string, value: string) {
      if (this === localStorage && storageKey === key && failures-- > 0) throw new DOMException('Synthetic pharmacy storage failure.', 'QuotaExceededError');
      return original.call(this, storageKey, value);
    };
  }, STORAGE_KEY);
  await page.getByTestId('pharmacy-submit').click();
  await expect(page.getByTestId('pharmacy-error')).toBeVisible();
  await expect(page.getByTestId('pharmacy-submit')).toBeEnabled();
  await page.getByTestId('pharmacy-submit').dblclick();
  await expect(page.getByText('Pedido de ejemplo guardado',{exact:true})).toBeVisible();
  const saved=await page.evaluate(key=>JSON.parse(localStorage.getItem(key)!),STORAGE_KEY);
  expect(saved.pharmacy.orders).toHaveLength(1);expect(saved.pharmacy.cart).toHaveLength(0);
  expect(saved.pharmacy.orders[0].totalCents).toBe(54900);expect(saved.pharmacy.orders[0].paymentMethod).toBe('card');
  await page.waitForTimeout(650);
  await page.getByRole('button',{name:'Ver pedido',exact:true}).click();
  await expect(page.getByText('Tu pedido',{exact:true})).toBeVisible();
  await page.screenshot({path:'test-results/pharmacy/order-'+width+'.png'});
  await page.getByRole('button',{name:'Ayuda con mi pedido',exact:true}).click();
  await page.getByRole('button',{name:'Solicitar cancelación',exact:true}).click();
  await expect(page.getByText('Pedido de ejemplo cancelado.',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Volver a mis compras',exact:true}).click();
  await page.getByRole('tab',{name:'Apego',exact:true}).click();
  await page.getByRole('button',{name:'Ver programa',exact:true}).click();
  await page.getByRole('checkbox',{name:'Acepto las condiciones del programa de demostración',exact:true}).click();
  await page.getByRole('button',{name:'Solicitar inscripción de ejemplo',exact:true}).click();
  await expect(page.getByText('En revisión · Demostración',{exact:true})).toBeVisible();
  await page.getByRole('tab',{name:'Productos',exact:true}).click();
  await page.getByRole('button',{name:'Agregar Medicamento A',exact:true}).click();
  await page.getByTestId('pharmacy-seller-option-demo-medicine').click();
  await page.getByTestId('pharmacy-seller-add').click();
  await page.getByTestId('pharmacy-cart').click();await page.getByTestId('pharmacy-checkout').click();
  await expect(page.getByRole('button',{name:'Continuar con ejemplo',exact:true})).toBeDisabled();
  await page.getByRole('checkbox',{name:'Usar receta ficticia de ejemplo',exact:true}).click();
  await page.getByRole('button',{name:'Continuar con ejemplo',exact:true}).click();
  await expect(page.getByLabel('Código postal',{exact:true})).toHaveValue('03100');
  await page.reload();await expect(page.getByTestId('pharmacy-cart')).toBeVisible();
  const final=await page.evaluate(key=>JSON.parse(localStorage.getItem(key)!),STORAGE_KEY);
  expect(final.pharmacy.orders).toHaveLength(1);expect(final.pharmacy.orders[0].status).toBe('cancelled');expect(final.pharmacy.programRequests).toHaveLength(1);expect(final.pharmacy.cart).toHaveLength(1);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false);
  expect(errors).toEqual([]);expect(posts).toEqual([]);
  results.push({width,checks:'filters,empty,product,cart,address,payment-demo,persistence-failure-retry,double-submit,order,cancel,program,prescription,reload,no-overflow',errors,posts});
  await context.close();
 }
 await writeFile('test-results/pharmacy/web-result.json',JSON.stringify(results,null,2));
 console.log(JSON.stringify(results));
 } finally {await browser.close();}
}
main().catch(e=>{console.error(e);process.exitCode=1;});
