import { chromium, expect } from '@playwright/test';
async function main() {
  const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe' });
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
  const origin = process.env.KLINI_VERIFY_ORIGIN || 'http://127.0.0.1:8096';
  const providerRequests: string[] = [];
  await page.route('**/*', async route => {
    if (route.request().method() === 'POST') { providerRequests.push(route.request().url()); return route.abort(); }
    if (new URL(route.request().url()).origin !== new URL(origin).origin) return route.abort();
    return route.continue();
  });
  try {
    await page.goto(origin);
    await page.getByTestId('home-tab-archive').click();
    await page.getByTestId('menu-history').click();
    await expect(page.getByTestId('history-categories').getByRole('button')).toHaveCount(8);
    await page.waitForTimeout(450);
    const box = await page.getByTestId('archive-popup').boundingBox();
    const searchBox = await page.getByTestId('archive-search').boundingBox();
    await page.getByTestId('history-filter-button').click();
    await expect(page.getByTestId('history-filter-panel')).toBeVisible();
    await page.waitForTimeout(350);
    const filterBox = await page.getByTestId('history-filter-panel').boundingBox();
    for (const trigger of ['calendar-from', 'calendar-to', 'filter-specialty', 'filter-institution']) {
      await page.getByTestId(trigger).click();
      await expect(page.getByTestId('history-filter-selector')).toBeVisible();
      expect(await page.getByTestId('history-filter-panel').boundingBox()).toEqual(filterBox);
      await page.getByTestId('history-filter-selector-close').click();
      await expect(page.getByTestId('history-filter-selector')).toHaveCount(0);
    }
    await page.screenshot({ path: 'test-results/history-filters-popup.png' });
    await page.getByTestId('filter-specialty').click();
    const specialtyBox = await page.getByTestId('history-filter-selector').boundingBox();
    const specialtySearchBox = await page.getByTestId('specialty-catalog-search').boundingBox();
    await page.getByTestId('filter-options-scroll').evaluate(element => { element.scrollTop = 500; });
    expect(await page.getByTestId('specialty-catalog-search').boundingBox()).toEqual(specialtySearchBox);
    await page.getByTestId('specialty-catalog-search').fill('cardiologia pediatrica');
    expect(await page.getByTestId('history-filter-selector').boundingBox()).toEqual(specialtyBox);
    await page.getByRole('button', { name: 'Cardiología Pediátrica', exact: true }).click();
    await expect(page.getByTestId('filter-specialty')).toContainText('Cardiología Pediátrica');
    await expect(page.getByTestId('history-filter-selector')).toHaveCount(0);
    await page.getByTestId('filter-specialty').click();
    await page.getByRole('button', { name: 'Todas las especialidades', exact: true }).click();
    await page.getByTestId('filter-from').fill('01/01/2099');
    await page.getByTestId('history-filter-close').click();
    await expect(page.getByTestId('history-search-results')).toHaveCount(0);
    await page.getByTestId('history-filter-button').click();
    await expect(page.getByTestId('filter-from')).toHaveValue('');
    await page.getByTestId('filter-from').fill('31/02/2026');
    await page.getByTestId('history-filter-done').click();
    await expect(page.getByRole('alert')).toContainText('fechas válidas');
    await page.getByTestId('filter-from').fill('01/01/2099');
    await page.getByTestId('history-filter-done').click();
    await expect(page.getByTestId('history-categories')).toHaveCount(0);
    await expect(page.getByText('Mi historial', { exact: true })).toBeVisible();
    await expect(page.getByTestId('history-records')).toBeVisible();
    await expect(page.getByTestId('history-records').getByTestId(/^history-row-/)).toHaveCount(0);
    expect((await page.getByTestId('archive-search').boundingBox())!.y).toBeCloseTo(searchBox!.y, 0);
    await expect(page.getByTestId('history-clear-filters')).toBeVisible();
    const filteredResultsBox = await page.getByTestId('history-records').boundingBox();
    await page.getByTestId('history-clear-filters').click();
    await expect(page.getByTestId('history-clear-filters')).toHaveCount(0);
    await expect(page.getByText('Mi historial', { exact: true })).toBeVisible();
    await expect(page.getByTestId('history-categories')).toHaveCount(0);
    await expect(page.getByTestId('history-search-results')).toHaveCount(0);
    await expect(page.getByTestId('history-records').getByTestId(/^history-row-/)).not.toHaveCount(0);
    expect((await page.getByTestId('history-records').boundingBox())!.y).toBeCloseTo(filteredResultsBox!.y, 0);
    await page.getByTestId('archive-detail-back').click();
    await expect(page.getByTestId('history-categories')).toBeVisible();
    await page.screenshot({ path: 'test-results/history-categories.png' });
    await page.getByTestId('history-category-Alergia').click();
    await page.getByTestId('add-archive-item').click();
    await page.getByTestId('registration-document').click();
    await expect(page.getByTestId('record-entry-screen')).toBeVisible();
    await page.getByTestId('record-type-text').click();
    await expect(page.getByTestId('record-categories')).toHaveCount(0);
    await expect(page.getByTestId('record-text-popup')).toBeVisible();
    await page.getByTestId('record-text-save').click();
    await expect(page.getByRole('alert')).toContainText('Escribe tu registro');
    await page.screenshot({ path: 'test-results/record-text-popup.png' });
    await page.getByTestId('record-text-input').fill('Alergia de prueba');
    await page.getByTestId('record-text-save').click();
    await expect(page.getByTestId('record-text-popup')).toHaveCount(0);
    await expect(page.getByTestId('record-categories')).toBeVisible();
    await page.waitForTimeout(450);
    const categoryPopup = await page.getByTestId('record-category-popup').boundingBox();
    expect(categoryPopup!.x).toBeGreaterThan(0);
    expect(categoryPopup!.y).toBeGreaterThan(0);
    expect(categoryPopup!.y + categoryPopup!.height).toBeLessThan(844);
    await page.screenshot({ path: 'test-results/record-categories.png' });
    await page.getByTestId('record-category-Alergia').click();
    await expect(page.getByTestId('record-category-popup')).toBeVisible();
    await page.getByTestId('record-category-continue').click();
    await expect(page.getByTestId('record-review-sheet')).toBeVisible();
    await page.getByTestId('record-review-edit').click();
    await expect(page.getByTestId('photo-review-title')).toHaveValue('Alergia de prueba');
    await page.getByTestId('record-review-edit').click();
    await page.getByTestId('save-record').click();
    await expect(page.getByText('Alergia de prueba', { exact: true })).toBeVisible();
    await page.getByTestId('archive-detail-back').click();
    await page.getByTestId('archive-search').fill('Alergia de prueba');
    await expect(page.getByTestId('history-search-results')).toContainText('Alergia de prueba');
    expect((await page.getByTestId('archive-popup').boundingBox())!.y).toBeCloseTo(box!.y, 0);
    await page.getByTestId('archive-search').fill('');
    await page.setViewportSize({ width: 320, height: 700 });
    await page.screenshot({ path: 'test-results/history-categories-small.png' });
    const grid = await page.getByTestId('history-categories').boundingBox();
    expect(grid!.x).toBeGreaterThanOrEqual(0);
    expect(grid!.x + grid!.width).toBeLessThanOrEqual(320);
    await page.getByTestId('add-archive-item').click();
    await page.getByTestId('registration-document').click();
    await expect(page.getByTestId('record-entry-screen')).toBeVisible();
    await page.getByTestId('record-type-text').click();
    await expect(page.getByTestId('record-categories')).toHaveCount(0);
    await page.getByTestId('record-text-input').fill('Registro sin categoría');
    await page.getByTestId('record-text-save').click();
    await expect(page.getByTestId('record-categories')).toBeVisible();
    await page.waitForTimeout(450);
    await expect(page.getByTestId('record-category-continue')).toBeDisabled();
    await expect(page.getByTestId('record-entry-screen')).toHaveCount(0);
    await page.getByTestId('record-category-Todos').click();
    await page.getByTestId('record-category-continue').click();
    await expect(page.getByTestId('record-review-sheet')).toBeVisible();
    await page.getByTestId('record-review-edit').click();
    await expect(page.getByTestId('photo-review-title')).toHaveValue('Registro sin categoría');
    await page.getByTestId('record-review-edit').click();
    await page.getByTestId('save-record').click();
    await expect(page.getByText('Registro sin categoría', { exact: true })).toBeVisible();
    await expect(page.getByText('Alergia de prueba', { exact: true })).toBeVisible();
    expect(providerRequests).toEqual([]);
    console.log('PASS capture text before category and final save, history filters/search, stable popup and small viewport');
  } finally { await browser.close(); }
}
main().catch(error => { console.error(error); process.exitCode = 1; });
